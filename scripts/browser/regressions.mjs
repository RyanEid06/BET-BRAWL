import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs';
const require = createRequire(process.env.BRAWL_PLAYWRIGHT_MODULE || import.meta.url);
const { chromium } = require('playwright');
const browser = await chromium.launch({ executablePath: process.env.BRAWL_CHROME_EXECUTABLE, headless: true });
const errors = [], checks = [];
fs.mkdirSync('output/playwright', { recursive: true });
const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
page.on('pageerror', error => errors.push(String(error)));
const run = fn => page.evaluate(fn);
const settle = () => page.waitForTimeout(50);
try {
  await page.goto(`${process.env.BRAWL_BROWSER_URL || 'http://127.0.0.1:5175'}/scripts/browser/regressions.html`);
  await page.waitForFunction(() => window.__regression?.client);
  await run(() => { const a = window.__regression; a.client.hostGame('Alexandra', '🦊'); });
  await run(() => { const a = window.__regression; a.open(); a.reset('circuit_sprint'); a.join(); }); await settle();
  const tile = page.getByRole('button', { name: /^Row 1, column 1,/ });
  const rotation = () => tile.getAttribute('aria-label');
  const initial = await rotation();
  await tile.click(); assert.notEqual(await rotation(), initial);
  await tile.click(); await tile.click();
  const optimistic = await rotation();
  await run(() => window.__regression.flush(1)); await settle(); assert.equal(await rotation(), optimistic);
  await run(() => window.__regression.flush()); await settle(); assert.equal(await rotation(), optimistic);
  await tile.click(); await run(() => window.__regression.reject()); await settle(); assert.equal(await rotation(), optimistic);
  await run(() => window.__regression.solve()); await settle(); assert.equal(await tile.isDisabled(), true);
  checks.push('Circuit immediate/rapid/partial/batched/rejected/solved');
  await run(() => window.__regression.reset('circuit_sprint')); await settle();
  await run(() => { window.__regression.reads = 0; });
  await page.waitForTimeout(1250);
  assert.equal(await run(() => window.__regression.reads), 0, 'Clock rerendered Circuit');
  checks.push('Clock: zero game rerenders during 1.25s sampling');
  await run(() => window.__regression.reset('memory_heist')); await settle();
  const cell = page.getByRole('button', { name: /Row 1, column 1:/ });
  await cell.click(); await run(() => window.__regression.flush()); await settle();
  await page.getByRole('button', { name: /^B ●$/ }).click(); await cell.click();
  assert.match(await cell.innerText(), /B/);
  await run(() => { window.__regression.queue = []; window.__regression.socket.close(); }); await settle(); assert.equal(await page.locator('.v2-game button:enabled').count(), 0);
  await page.waitForFunction(() => window.__regression.socket.readyState === 0);
  await run(() => window.__regression.open()); await settle(); assert.equal(await page.locator('.v2-game button:enabled').count(), 0, 'Controls enabled before seat restoration');
  await run(() => window.__regression.join()); await settle(); assert.match(await cell.innerText(), /A/);
  assert.equal(await page.getByRole('button', { name: 'Undo', exact: true }).isDisabled(), true);
  checks.push('Memory: reconnect authoritative draft/undo, offline/pre-join controls paused');
  await run(() => window.__regression.reset('mirror_trouble')); await settle();
  await page.getByRole('button', { name: /^Choice 1/ }).click();
  const old = await run(() => window.__regression.queue[0]);
  await run(() => window.__regression.reject()); await settle(); assert.equal(await page.getByRole('alert').count(), 1);
  await run(() => window.__regression.step(4000)); await settle(); assert.equal(await page.getByRole('alert').count(), 0);
  assert.match(await page.locator('.v2-notice').first().innerText(), /Correct choice:/);
  assert.equal(await page.locator('.v2-correct').count(), 1);
  await page.screenshot({ path: 'output/playwright/mirror-reveal.png', fullPage: true });
  await run(() => window.__regression.step(1000)); await settle();
  await page.evaluate(old => window.__regression.ack({ ...old, accepted: false, reason: 'Stale error' }), old); await settle();
  assert.equal(await page.getByRole('alert').count(), 0);
  await run(() => window.__regression.reset('treasure_tug')); await settle();
  await page.evaluate(old => window.__regression.ack({ ...old, accepted: false, reason: 'Stale match' }), old); await settle(); assert.equal(await page.getByRole('alert').count(), 0);
  checks.push('Mirror reveal and stale stage/match feedback');
  await page.getByRole('button', { name: 'Balanced 3 / 3 / 4', exact: true }).click();
  assert.equal(await page.getByRole('button', { name: /Lock allocation 10/ }).isEnabled(), true);
  await page.getByRole('button', { name: 'Clear', exact: true }).click();
  await page.getByLabel('Set lane 3 energy', { exact: true }).fill('10');
  await page.getByRole('button', { name: /Lock allocation 10/ }).click();
  assert.deepEqual(await run(() => window.__regression.queue.at(-1).allocation), [0, 0, 10]);
  checks.push('Treasure preset/direct allocation remains exactly ten');
  await run(() => window.__regression.reset('pocket_territory')); await settle();
  assert.match(await page.getByLabel('Territory scores').innerText(), /Alexandra[\s\S]*1 points[\s\S]*Benjamin[\s\S]*1 points/);
  assert.equal(await page.locator('.v2-owner-a strong').last().innerText(), '🦊');
  checks.push('Territory identities and weighted scores');
  await run(() => window.__regression.socket.close());
  await page.waitForFunction(() => window.__regression.socket.readyState === 0);
  await run(() => { window.__regression.open(); window.__regression.failJoin(); }); await settle();
  assert.equal(await run(() => window.__regression.client.phase), 'ENTRY');
  assert.equal(await run(() => window.__regression.client.status), 'ERROR');
  assert.match(await run(() => window.__regression.client.errorMessage), /Room no longer exists/);
  checks.push('Failed reconnect returns to entry with recoverable error');
  await run(() => window.__regression.remount()); await settle();
  await run(() => window.__regression.client.hostGame('Alexandra', '🦊'));
  await run(() => { const a = window.__regression; a.open(); a.reset('memory_heist'); a.join(); }); await settle();
  for (const width of [360, 390, 1366]) {
    await page.setViewportSize({ width, height: width === 360 ? 640 : 844 });
    await run(() => { window.__regression.reset('memory_heist'); window.__regression.payout(); }); await settle();
    const details = page.locator('details');
    assert.equal(await details.getAttribute('open'), null);
    assert.equal(await page.getByRole('group', { name: 'Original memory board' }).isVisible(), false);
    const next = page.getByRole('button', { name: /PROCEED TO QUALIFIER/ });
    const box = await next.boundingBox(); assert.ok(box.y >= 0 && box.y + box.height <= (width === 360 ? 640 : 844), 'Host action below fold');
    await page.getByText('View details', { exact: true }).click();
    assert.equal(await page.getByRole('group', { name: 'Original memory board' }).isVisible(), true);
    await next.click();
    await page.screenshot({ path: `output/playwright/${width}-payout.png`, fullPage: true });
  }
  checks.push('Payout: closed details, reachable/actionable host continuation at 3 widths');
  assert.deepEqual(errors, []);
} catch (error) { errors.push(String(error)); process.exitCode = 1; }
finally { await browser.close(); fs.writeFileSync('output/playwright/regressions.json', JSON.stringify({ checks, errors }, null, 2)); console.log(JSON.stringify({ checks, errors }, null, 2)); }

import { createRequire } from 'node:module';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import process from 'node:process';
const require = createRequire(process.env.BRAWL_PLAYWRIGHT_MODULE || import.meta.url);
const { chromium } = require('playwright');
const browser = await chromium.launch({ headless: true, executablePath: process.env.BRAWL_CHROME_EXECUTABLE || undefined });
const checks = [];
const errors = [];
fs.mkdirSync('output/playwright', { recursive: true });
try {
  for (const [width, height] of [[360, 640], [390, 844], [768, 1024], [1366, 768]]) {
    const context = await browser.newContext({ viewport: { width, height }, hasTouch: width < 800, isMobile: width < 800 });
    const page = await context.newPage();
    page.on('pageerror', error => errors.push(String(error)));
    await page.goto(`${process.env.BRAWL_BROWSER_URL || 'http://127.0.0.1:5175'}/scripts/browser/pinpoint.html`);
    const map = page.getByTestId('pinpoint-map');
    await map.waitFor();
    const box = await map.boundingBox();
    assert.ok(box && box.width / box.height >= 1.99 && box.width / box.height <= 2.01, `${width}: full world aspect ratio`);
    assert.equal(await page.getByTestId('pinpoint-world').evaluate(el => getComputedStyle(el).getPropertyValue('--bp-zoom')), '1');
    const lockBox = await page.getByRole('button', { name: 'Lock guess' }).boundingBox();
    assert.ok(lockBox && lockBox.x >= 0 && lockBox.x + lockBox.width <= width && lockBox.y + lockBox.height <= height, `${width}: lock action stays reachable`);
    const scoreBox = await page.getByText('Awaiting pin...', { exact: true }).first().boundingBox();
    assert.ok(scoreBox && scoreBox.y >= 0 && scoreBox.y + scoreBox.height <= height, `${width}: status stays in viewport`);
    if (width === 360) {
      await map.click({ position: { x: box.width * 0.58, y: box.height * 0.36 } });
      await page.screenshot({ path: 'output/playwright/pinpoint-360x640.png', fullPage: true });
    }
    await context.close();
  }
  checks.push('full world remains 2:1 at 360, 390, 768 and 1366 widths');

  const page = await browser.newPage({ viewport: { width: 390, height: 844 } });
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto(`${process.env.BRAWL_BROWSER_URL || 'http://127.0.0.1:5175'}/scripts/browser/pinpoint.html`);
  const map = page.getByTestId('pinpoint-map');
  const box = await map.boundingBox();
  assert.ok(box);
  assert.equal(await page.getByText('Awaiting pin...', { exact: true }).count(), 2, 'zero scores without pins stay pending');
  await map.click({ position: { x: box.width * 0.25, y: box.height * 0.4 } });
  assert.equal(await page.getByTestId('draft-pin').count(), 1, 'tap creates local draft');
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 0, 'tap does not submit');
  await map.click({ position: { x: box.width * 0.7, y: box.height * 0.6 } });
  const draft = await page.getByTestId('draft-pin').getAttribute('style');
  const draftLeft = Number(draft?.match(/left:\s*([\d.]+)%/)?.[1]);
  assert.ok(draftLeft > 70 && draftLeft < 71, `tap coordinate respects map border: ${draft}`);
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 0, 'tap updates same local draft');
  await page.evaluate(() => {
    const lock = document.querySelector('button[aria-label="Lock guess"]');
    lock.click(); lock.click();
  });
  const firstAction = await page.evaluate(() => window.__pinpoint.actions[0]);
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 1);
  assert.ok(Math.abs(firstAction.normX - draftLeft / 100) < 0.0001);
  assert.equal(await page.getByRole('button', { name: 'Lock guess' }).isDisabled(), true, 'lock cannot be submitted twice');
  checks.push('transformed coordinate draft updates locally; lock sends PIN exactly once');

  await page.reload();
  await page.evaluate(() => { window.__pinpoint.spectator = true; window.__pinpoint.refresh(); });
  await page.waitForTimeout(50);
  const spectatorBox = await map.boundingBox();
  assert.ok(spectatorBox);
  await map.click({ position: { x: spectatorBox.width * 0.4, y: spectatorBox.height * 0.3 } });
  assert.equal(await page.getByTestId('draft-pin').count(), 0, 'spectator cannot draft');
  await page.getByRole('button', { name: 'Zoom in' }).click();
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 0, 'spectator navigation emits no guess');
  checks.push('spectators can navigate without placing or submitting guesses');

  await page.reload();
  const mapBox = await map.boundingBox();
  assert.ok(mapBox);
  const world = page.getByTestId('pinpoint-world');
  await page.getByRole('button', { name: 'Zoom in' }).click();
  await page.getByRole('button', { name: 'Zoom in' }).click();
  await page.getByRole('button', { name: 'Zoom in' }).click();
  await page.getByRole('button', { name: 'Zoom in' }).click();
  assert.equal(await world.evaluate(el => getComputedStyle(el).getPropertyValue('--bp-zoom')), '4');
  assert.equal(await page.getByRole('button', { name: 'Zoom in' }).isDisabled(), true, 'zoom-in disables at the 4× limit');
  assert.equal(await world.evaluate(el => getComputedStyle(el).getPropertyValue('--bp-zoom')), '4', 'zoom is capped at 4');
  const start = await map.boundingBox();
  assert.ok(start);
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2);
  await page.mouse.down(); await page.mouse.move(start.x + start.width / 2 - 120, start.y + start.height / 2 - 80); await page.mouse.up();
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 0, 'pan never submits a guess');
  await page.getByRole('button', { name: 'Reset map' }).click();
  assert.equal(await world.evaluate(el => getComputedStyle(el).getPropertyValue('--bp-zoom')), '1');
  assert.equal(await world.evaluate(el => getComputedStyle(el).getPropertyValue('--bp-x')), '0px');
  assert.equal(await world.evaluate(el => getComputedStyle(el).getPropertyValue('--bp-y')), '0px');
  await page.getByRole('button', { name: 'Zoom in' }).click();
  const zoomBox = await map.boundingBox();
  assert.ok(zoomBox);
  await page.mouse.move(zoomBox.x + zoomBox.width / 2, zoomBox.y + zoomBox.height / 2);
  await page.mouse.down(); await page.mouse.move(zoomBox.x + zoomBox.width / 2 - 100, zoomBox.y + zoomBox.height / 2 - 55); await page.mouse.up();
  const transformedBox = await map.boundingBox();
  const transformed = await world.evaluate(el => ({ zoom: Number(getComputedStyle(el).getPropertyValue('--bp-zoom')), x: parseFloat(getComputedStyle(el).getPropertyValue('--bp-x')), y: parseFloat(getComputedStyle(el).getPropertyValue('--bp-y')) }));
  assert.ok(transformedBox);
  const tapX = transformedBox.width * 0.63, tapY = transformedBox.height * 0.58;
  const content = await map.evaluate(el => ({ left: el.clientLeft, top: el.clientTop, width: el.clientWidth, height: el.clientHeight }));
  await map.evaluate(el => el.addEventListener('pointerup', event => { window.__lastPointer = { x: event.clientX, y: event.clientY }; }, { capture: true, once: true }));
  await map.click({ position: { x: tapX, y: tapY } });
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 0, 'transformed-coordinate tap remains a draft');
  const actualPoint = await page.evaluate(() => window.__lastPointer);
  const expectedX = Math.max(0, Math.min(1, (actualPoint.x - transformedBox.x - content.left - transformed.x) / (content.width * transformed.zoom)));
  const expectedY = Math.max(0, Math.min(1, (actualPoint.y - transformedBox.y - content.top - transformed.y) / (content.height * transformed.zoom)));
  await page.getByRole('button', { name: 'Lock guess' }).click();
  const transformedAction = await page.evaluate(() => window.__pinpoint.actions[0]);
  assert.ok(Math.abs(transformedAction.normX - expectedX) < 0.002, `x action ${transformedAction.normX} expected ${expectedX}; view ${JSON.stringify(transformed)}, content ${JSON.stringify(content)}`);
  assert.ok(Math.abs(transformedAction.normY - expectedY) < 0.002, `y action ${transformedAction.normY} expected ${expectedY}; view ${JSON.stringify(transformed)}, content ${JSON.stringify(content)}`);
  checks.push('zoom limit, pan-without-guess, reset, transformed coordinates');

  await page.reload();
  const pinchMap = page.getByTestId('pinpoint-map');
  const pinchBox = await pinchMap.boundingBox(); assert.ok(pinchBox);
  await pinchMap.dispatchEvent('wheel', { deltaY: -120, clientX: pinchBox.x + pinchBox.width / 2, clientY: pinchBox.y + pinchBox.height / 2 });
  assert.ok(Number(await page.getByTestId('pinpoint-world').evaluate(el => getComputedStyle(el).getPropertyValue('--bp-zoom'))) > 1, 'wheel zooms the map');
  assert.equal(await page.getByTestId('draft-pin').count(), 0, 'wheel does not create a draft');
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 0, 'wheel does not submit a guess');
  await page.getByRole('button', { name: 'Reset map' }).click();
  const cdp = await page.context().newCDPSession(page);
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [{ x: pinchBox.x + pinchBox.width * 0.4, y: pinchBox.y + pinchBox.height / 2, id: 1 }, { x: pinchBox.x + pinchBox.width * 0.6, y: pinchBox.y + pinchBox.height / 2, id: 2 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchMove', touchPoints: [{ x: pinchBox.x + pinchBox.width * 0.3, y: pinchBox.y + pinchBox.height / 2, id: 1 }, { x: pinchBox.x + pinchBox.width * 0.7, y: pinchBox.y + pinchBox.height / 2, id: 2 }] });
  await cdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.ok(Number(await page.getByTestId('pinpoint-world').evaluate(el => getComputedStyle(el).getPropertyValue('--bp-zoom'))) > 1, 'pinch zooms the map');
  assert.equal(await page.getByTestId('draft-pin').count(), 0, 'pinch never leaves a draft');
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 0, 'pinch never submits a guess');
  checks.push('two-finger pinch zoom without guess placement or submission');

  const cancelContext = await browser.newContext({ viewport: { width: 360, height: 640 }, hasTouch: true, isMobile: true });
  const cancelPage = await cancelContext.newPage();
  cancelPage.on('pageerror', error => errors.push(String(error)));
  await cancelPage.goto(`${process.env.BRAWL_BROWSER_URL || 'http://127.0.0.1:5175'}/scripts/browser/pinpoint.html`);
  const cancelMapBox = await cancelPage.getByTestId('pinpoint-map').boundingBox(); assert.ok(cancelMapBox);
  const cancelCdp = await cancelContext.newCDPSession(cancelPage);
  const touch = { x: cancelMapBox.x + cancelMapBox.width * 0.4, y: cancelMapBox.y + cancelMapBox.height * 0.5, id: 3 };
  await cancelCdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [touch] });
  await cancelCdp.send('Input.dispatchTouchEvent', { type: 'touchCancel', touchPoints: [] });
  assert.equal(await cancelPage.getByTestId('draft-pin').count(), 0, 'cancel does not leave a draft');
  await cancelCdp.send('Input.dispatchTouchEvent', { type: 'touchStart', touchPoints: [touch] });
  await cancelCdp.send('Input.dispatchTouchEvent', { type: 'touchEnd', touchPoints: [] });
  assert.equal(await cancelPage.getByTestId('draft-pin').count(), 1, 'tap after last-pointer cancel places a draft');
  await cancelContext.close();
  checks.push('last-pointer cancel clears gesture suppression for the next tap');

  const resizeContext = await browser.newContext({ viewport: { width: 844, height: 390 } });
  const resizePage = await resizeContext.newPage();
  resizePage.on('pageerror', error => errors.push(String(error)));
  await resizePage.goto(`${process.env.BRAWL_BROWSER_URL || 'http://127.0.0.1:5175'}/scripts/browser/pinpoint.html`);
  const resizeMap = resizePage.getByTestId('pinpoint-map');
  for (let i = 0; i < 4; i++) await resizePage.getByRole('button', { name: 'Zoom in' }).click();
  let resizeBox = await resizeMap.boundingBox(); assert.ok(resizeBox);
  await resizePage.mouse.move(resizeBox.x + resizeBox.width / 2, resizeBox.y + resizeBox.height / 2);
  await resizePage.mouse.down(); await resizePage.mouse.move(resizeBox.x - 1000, resizeBox.y - 1000); await resizePage.mouse.up();
  const coversWorld = () => resizeMap.evaluate(map => {
    const world = map.querySelector('[data-testid="pinpoint-world"]');
    const frame = map.getBoundingClientRect(), view = world.getBoundingClientRect();
    const left = frame.left + map.clientLeft, top = frame.top + map.clientTop;
    return view.left <= left + 1 && view.top <= top + 1 && view.right >= left + map.clientWidth - 1 && view.bottom >= top + map.clientHeight - 1;
  });
  assert.equal(await coversWorld(), true, 'edge pan fills the original viewport');
  await resizePage.setViewportSize({ width: 390, height: 844 });
  await resizePage.waitForTimeout(100);
  assert.equal(await coversWorld(), true, 'resize clamps the edge pan with no blank map area');
  assert.ok(Number(await resizePage.getByTestId('pinpoint-world').evaluate(el => getComputedStyle(el).getPropertyValue('--bp-zoom'))) <= 4);
  await resizeContext.close();
  checks.push('landscape-to-portrait resize clamps an edge pan and keeps the map covered');

  await page.reload();
  await page.evaluate(() => { window.__pinpoint.locked = true; window.__pinpoint.refresh(); });
  await page.waitForTimeout(50);
  const lockedMapBox = await map.boundingBox();
  assert.ok(lockedMapBox);
  await map.click({ position: { x: lockedMapBox.width * 0.2, y: lockedMapBox.height * 0.2 } });
  assert.equal(await page.getByTestId('draft-pin').count(), 0, 'locked authoritative pin cannot be edited');
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 0);
  await page.getByRole('button', { name: 'Zoom in' }).click();
  const lockedPanBox = await map.boundingBox(); assert.ok(lockedPanBox);
  await page.mouse.move(lockedPanBox.x + lockedPanBox.width / 2, lockedPanBox.y + lockedPanBox.height / 2);
  await page.mouse.down(); await page.mouse.move(lockedPanBox.x + lockedPanBox.width / 2 - 40, lockedPanBox.y + lockedPanBox.height / 2 - 20); await page.mouse.up();
  assert.equal(await page.evaluate(() => window.__pinpoint.actions.length), 0, 'locked player can still navigate without resubmitting');
  checks.push('authoritative locked guess cannot be changed');
  assert.deepEqual(errors, []);
} catch (error) { errors.push(String(error)); process.exitCode = 1; }
finally { await browser.close(); fs.mkdirSync('output/playwright', { recursive: true }); fs.writeFileSync('output/playwright/pinpoint.json', JSON.stringify({ checks, errors }, null, 2)); console.log(JSON.stringify({ checks, errors }, null, 2)); }
